#!/usr/bin/env bash
#
# Builds /etc/tyche/runtime.env, the single environment file both services read.
#
# Three sources, in increasing precedence:
#
#   1. /opt/tyche/release/production.env  - committed, non-secret, environment-agnostic
#                                   configuration and feature flags.
#   2. SSM Parameter Store        - non-secret values only Terraform knows
#                                   (domains, origins, database endpoint).
#   3. Secrets Manager            - the RDS-managed master credentials and the
#                                   operator-provisioned runtime secrets.
#
# Nothing is ever echoed: the file is written with 0600 and the script prints
# only key names. Missing required input aborts, because a backend that boots
# with an empty provider key would fail later, during a live turn, in a way
# that looks like a model outage instead of a misconfiguration.
set -euo pipefail

# shellcheck disable=SC1091
source /etc/tyche/deploy.conf

TARGET="/etc/tyche/runtime.env"
STAGING="$(mktemp /etc/tyche/runtime.env.XXXXXX)"
chmod 0600 "$STAGING"
trap 'rm -f "$STAGING"' EXIT

if [ ! -f /opt/tyche/release/production.env ]; then
  echo "[render-env] FATAL: /opt/tyche/release/production.env missing from the release bundle." >&2
  exit 1
fi

echo "# Generated by render-env.sh at $(date --iso-8601=seconds). Do not edit." >"$STAGING"

# --- 1. committed configuration -------------------------------------------
grep -E '^[A-Z_][A-Z_0-9]*=' /opt/tyche/release/production.env >>"$STAGING"

# --- 1b. on-chain addresses from the deployment manifest -------------------
# deployments/solana-<cluster>.json is the source of truth for program ids, so
# no address is duplicated into configuration where it could drift from what is
# actually deployed.
CLUSTER="$(grep -E '^TYCHE_SOLANA_CLUSTER=' "$STAGING" | cut -d= -f2-)"
[ -n "$CLUSTER" ] || {
  echo "[render-env] FATAL: TYCHE_SOLANA_CLUSTER is not set in production.env." >&2
  exit 1
}

MANIFEST="/opt/tyche/release/deployments/solana-$CLUSTER.json"
if [ ! -f "$MANIFEST" ]; then
  echo "[render-env] FATAL: $MANIFEST missing from the release bundle." >&2
  exit 1
fi

jq -re '
  {
    TYCHE_PROGRAM_ID: .tycheProgramId,
    TOKENOMICS_CORE_PROGRAM_ID: .tokenomicsCore.programId,
    TYCHE_SWITCHBOARD_ON_DEMAND_PROGRAM_ID: .switchboard.onDemandProgramId,
    TYCHE_SWITCHBOARD_ON_DEMAND_QUEUE: .switchboard.queueAddress,
    TYCHE_SWITCHBOARD_ON_DEMAND_QUEUE_PDA: .switchboard.queuePda
  }
  | to_entries[]
  | select(.value != null)
  | "\(.key)=\(.value)"
' "$MANIFEST" >>"$STAGING"

# --- 2. Terraform-managed configuration -----------------------------------
# Written as /tyche/<env>/config/<KEY>; the parameter name is the variable name.
aws ssm get-parameters-by-path \
  --path "$SSM_CONFIG_PATH" \
  --region "$AWS_REGION" \
  --query 'Parameters[].[Name,Value]' \
  --output text |
  while IFS=$'\t' read -r name value; do
    printf '%s=%s\n' "${name##*/}" "$value"
  done >>"$STAGING"

# The two keys the host needs to reach the rest of the configuration.
DB_SECRET_ARN="$(grep -E '^TYCHE_DB_SECRET_ARN=' "$STAGING" | cut -d= -f2-)"
RUNTIME_SECRET_ARN="$(grep -E '^TYCHE_RUNTIME_SECRET_ARN=' "$STAGING" | cut -d= -f2-)"
DB_HOST="$(grep -E '^TYCHE_DB_HOST=' "$STAGING" | cut -d= -f2-)"
DB_PORT="$(grep -E '^TYCHE_DB_PORT=' "$STAGING" | cut -d= -f2-)"
DB_NAME="$(grep -E '^TYCHE_DB_NAME=' "$STAGING" | cut -d= -f2-)"

for required in DB_SECRET_ARN RUNTIME_SECRET_ARN DB_HOST DB_PORT DB_NAME; do
  if [ -z "${!required}" ]; then
    echo "[render-env] FATAL: $required is not in Parameter Store under $SSM_CONFIG_PATH." >&2
    exit 1
  fi
done

# --- 3a. database credentials ---------------------------------------------
DB_CREDENTIALS="$(aws secretsmanager get-secret-value \
  --secret-id "$DB_SECRET_ARN" \
  --region "$AWS_REGION" \
  --query SecretString --output text)"

DB_USER="$(jq -re '.username' <<<"$DB_CREDENTIALS")"
DB_PASSWORD="$(jq -re '.password' <<<"$DB_CREDENTIALS")"

# Percent-encode the password: an RDS-generated password can contain characters
# that are not legal in a URL userinfo component.
DB_PASSWORD_ENCODED="$(jq -rn --arg p "$DB_PASSWORD" '$p|@uri')"

# RDS requires TLS and presents an Amazon-issued certificate. `require` gives
# an encrypted connection; the pg driver in apps/api and apps/worker does not
# pin the RDS CA bundle, so verify-full is not claimed here.
printf 'DATABASE_URL=postgresql://%s:%s@%s:%s/%s?sslmode=require\n' \
  "$DB_USER" "$DB_PASSWORD_ENCODED" "$DB_HOST" "$DB_PORT" "$DB_NAME" >>"$STAGING"

# --- 3b. operator-provisioned secrets -------------------------------------
RUNTIME_SECRETS="$(aws secretsmanager get-secret-value \
  --secret-id "$RUNTIME_SECRET_ARN" \
  --region "$AWS_REGION" \
  --query SecretString --output text)"

if ! jq -e 'type == "object"' >/dev/null 2>&1 <<<"$RUNTIME_SECRETS"; then
  echo "[render-env] FATAL: the runtime secret is not a JSON object." >&2
  exit 1
fi

if [ "$(jq -r '.TYCHE_RUNTIME_SECRETS_PROVISIONED // "true"' <<<"$RUNTIME_SECRETS")" = "false" ]; then
  echo "[render-env] FATAL: the runtime secret still holds the Terraform placeholder." >&2
  echo "[render-env] Provision it with: aws secretsmanager put-secret-value --secret-id $RUNTIME_SECRET_ARN --secret-string file://secrets.json" >&2
  exit 1
fi

jq -r 'to_entries[] | select(.key != "TYCHE_RUNTIME_SECRETS_PROVISIONED") | "\(.key)=\(.value)"' \
  <<<"$RUNTIME_SECRETS" >>"$STAGING"

# --- validation ------------------------------------------------------------
# Keys without which the backend cannot serve a turn. Failing here, at deploy
# time, is the difference between a refused rollout and a broken live turn.
REQUIRED_KEYS=(
  DATABASE_URL
  REDIS_URL
  TYCHE_PROGRAM_ID
  TYCHE_SOLANA_RPC_URL
  WEB_ORIGIN
)

missing=()
for key in "${REQUIRED_KEYS[@]}"; do
  if ! grep -qE "^$key=.+" "$STAGING"; then
    missing+=("$key")
  fi
done

if [ "${#missing[@]}" -gt 0 ]; then
  echo "[render-env] FATAL: missing required configuration: ${missing[*]}" >&2
  exit 1
fi

# The LLM endpoint and model each have several accepted variable names
# (apps/api/src/llm.ts resolveRuleAgentConfig). Requiring one of each group
# matches the code instead of forcing a particular spelling. Without them the
# API still boots and then fails every rule and dealer request mid-turn, which
# is exactly the failure this gate exists to prevent.
has_any() {
  local key
  for key in "$@"; do
    if grep -qE "^$key=.+" "$STAGING"; then
      return 0
    fi
  done
  return 1
}

if ! has_any LLM_BASE_URL LLM_PRIMARY_BASE_URL; then
  echo "[render-env] FATAL: no LLM endpoint configured (LLM_BASE_URL or LLM_PRIMARY_BASE_URL)." >&2
  exit 1
fi

if ! has_any LLM_MODEL LLM_MODEL_INTERPRET LLM_PRIMARY_MODEL; then
  echo "[render-env] FATAL: no LLM model configured (LLM_MODEL, LLM_MODEL_INTERPRET or LLM_PRIMARY_MODEL)." >&2
  exit 1
fi

# The rule pipeline needs two independent compilers and the Jev semantic
# checker (apps/api/src/lifespan.ts getDealerRuntime). Without either the API
# boots and then fails every rule preflight closed.
if ! has_any LLM_MODEL_COMPILE_B; then
  echo "[render-env] FATAL: the second rule compiler is not configured (LLM_MODEL_COMPILE_B)." >&2
  exit 1
fi
if ! has_any API_KEY_OPENROUTER && ! has_any JEV_ENDPOINT; then
  echo "[render-env] FATAL: the Jev semantic checker has no credential (API_KEY_OPENROUTER for the default endpoint, or JEV_ENDPOINT with its own key)." >&2
  exit 1
fi

# Turn automation and rule precompilation both sign with the turn authority
# (apps/worker/src/turn-automation.ts, apps/worker/src/precompile-loop.ts).
# Without the keypair they throw on every tick while /health still reports
# healthy, so the container would look fine and no turn would ever advance.
if grep -qE '^(TYCHE_TURN_AUTOMATION_ENABLED|TYCHE_RULE_PRECOMPILE_ENABLED)=(1|true)$' "$STAGING" &&
  ! has_any TYCHE_TURN_AUTHORITY_KEYPAIR TYCHE_TURN_AUTHORITY_KEYPAIR_PATH; then
  echo "[render-env] FATAL: turn automation or rule precompilation is enabled but no turn authority keypair is configured (TYCHE_TURN_AUTHORITY_KEYPAIR or TYCHE_TURN_AUTHORITY_KEYPAIR_PATH)." >&2
  exit 1
fi

# Manual turn control drives turns without the automation loop and must never
# be reachable in production, even though Caddy also blocks the routes.
if grep -qE '^TYCHE_TURN_MANUAL_CONTROL_ENABLED=(1|true)$' "$STAGING"; then
  echo "[render-env] FATAL: TYCHE_TURN_MANUAL_CONTROL_ENABLED is test-only and must be false in production." >&2
  exit 1
fi

install -m 0600 "$STAGING" "$TARGET"
echo "[render-env] wrote $TARGET with $(grep -cE '^[A-Z_][A-Z_0-9]*=' "$TARGET") variables"
